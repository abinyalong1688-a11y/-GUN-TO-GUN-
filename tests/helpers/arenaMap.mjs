// 沙盘地图（示意）：半径 52 的圆形竞技场，三条通道 + 中央据点，与游戏内 Desert Outpost 的尺度一致
// 返回 AABB 列表 {minX,maxX,minZ,maxZ,top}，与 game.world.colliders 同构
export function createArenaMap() {
  const boxes = [
    // [-20,-12,12,24] 形式：[minX, minZ, w, h, h(高度)]
    [-20, -12, 12, 24, 3], [8, -12, 12, 24, 3],          // 中央通道两侧的大楼
    [-44, -30, 16, 18, 3], [-44, 12, 16, 18, 3],         // 左侧外圈建筑
    [28, -30, 16, 18, 3], [28, 12, 16, 18, 3],           // 右侧外圈建筑
    [-6, 10, 4, 3, 1.2], [2, -13, 4, 3, 1.2],            // 中门错位的矮墙
    [-26, -6, 3, 3, 1.2], [23, 3, 3, 3, 1.2],            // 侧通道掩体
    [-3, 22, 3, 2, 1.2], [1, -24, 3, 2, 1.2],            // 出生点前的掩体
    [-9, 36, 4, 2, 1.2], [5, 36, 4, 2, 1.2],
    [-9, -38, 4, 2, 1.2], [5, -38, 4, 2, 1.2],
    [-36, -4, 3, 8, 1.2], [33, -4, 3, 8, 1.2],           // 侧通道中段掩体
  ];
  const colliders = boxes.map(([minX, minZ, w, d, top]) => ({ minX, minZ, maxX: minX + w, maxZ: minZ + d, top }));
  return {
    colliders,
    spawns: { A: [0, 42], B: [0, -42] },
    hill: { pos: [0, 0], radius: 8 },
    bound: 52,
  };
}
